export type Word = keyof typeof words;
export function useCopy() {
  const { locale } = useI18n();
  const config = useSite();
  const index =
    ({ zh: 0, en: 1, ja: 2, ko: 3 } as const)[locale as Locale] ?? 0;
  return {
    locale: locale as Locale,
    t: (key: Word | string) =>
      config.text[key]?.[locale] ??
      (key in words ? words[key as Word][index] : key),
    c: (value: Copy) => value[locale as Locale] || value.en,
    line: (zh: string, en: string, ja: string, ko: string) =>
      [zh, en, ja, ko][index],
  };
}
